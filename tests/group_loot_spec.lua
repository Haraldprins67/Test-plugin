-- Pure party/raid loot behavior; executable without modification in Lua 5.0.
ClassicLootLogNS = {}
dofile("ClassicLootLog/GroupLoot.lua")
local GroupLoot = ClassicLootLogNS.GroupLoot
local passed = 0
local clock = 100

local function equal(actual, expected, message)
    assert(actual == expected, (message or "unexpected value") .. ": expected "
        .. tostring(expected) .. ", got " .. tostring(actual))
end

local function test(name, callback)
    clock = 100
    callback()
    passed = passed + 1
    print("PASS " .. name)
end

local function tracker(db)
    db = db or {}
    return GroupLoot.New(db, {
        now = function() return clock end,
        time = function() return 1700000000 + clock end,
    }), db
end

local function item(id, name)
    return "|cffa335ee|Hitem:" .. id .. ":0:0:0|h[" .. (name or ("Item " .. id)) .. "]|h|r"
end

test("item contexts remain separate and duplicate active roll IDs are safe", function()
    local model = tracker()
    local a = model:StartItem(item(1), "group", {rollID = 20})
    local repeated, duplicate = model:StartItem(item(1), "group", {rollID = 20})
    equal(repeated, a)
    equal(duplicate, true)
    equal(table.getn(model:Entries()), 1)
    local b = model:StartItem(item(1), "group", {rollID = 21})
    equal(model:ResolveContext(item(1), 20), a)
    equal(model:ResolveContext(item(1), 21), b)
    local found, reason = model:ResolveContext(item(1))
    equal(found, nil)
    equal(reason, "ambiguous")
    found, reason = model:StartItem(item(2), "group", {rollID = 20})
    equal(found, nil)
    equal(reason, "roll_id_conflict")
end)

test("manual rolls require an explicitly selected open item", function()
    local model = tracker()
    local a = model:StartItem(item(1), "master")
    local b = model:StartItem(item(2), "master")
    equal(model:GetActive(), nil)
    equal(model:Select(a.id), true)
    equal(model:GetActive(), a)
    equal(model:Select(999), false)
    equal(model:GetActive(), a)
    equal(model:Select(b), true)
    equal(model:GetActive(), b)
    model:Close(b.id, "closed_by_user")
    equal(model:GetActive(), nil)
end)

test("group ranks prioritize need over greed and retain choices", function()
    local model = tracker()
    local entry = model:StartItem(item(1), "group")
    equal(model:SetChoice(entry.id, "Alice", "Need"), true)
    equal(model:SetChoice(entry.id, "Bob", "Greed"), true)
    equal(model:SetChoice(entry.id, "Cara", "Need"), true)
    model:SetChoice(entry.id, "Dan", "Pass")
    model:AddRoll(entry.id, "Bob", 99, 1, 100, "Greed")
    model:AddRoll(entry.id, "Alice", 81, 1, 100, "Need")
    model:AddRoll(entry.id, "Cara", 75, 1, 100, "Need")
    local ranks = model:Rankings(entry)
    equal(ranks.highest.player, "Alice")
    equal(ranks.second.player, "Cara")
    equal(ranks.highest.value, 81)
    equal(entry.choices.bob.choice, "GREED")
    equal(entry.choices.dan.choice, "PASS")
    equal(entry.winner, nil)
    equal(model:AddBid(entry.id, "Alice", "need"), false)
    equal(entry.method, "group")
end)

test("distinct tied players and rerolls are shown without inventing a winner", function()
    local model = tracker()
    local entry = model:StartItem(item(1), "master")
    model:AddRoll(entry, "Bob", 88)
    model:AddRoll(entry, "Alice", 88)
    model:AddRoll(entry, "Cara", 62)
    local ranks = model:Rankings(entry)
    equal(ranks.highest.player, "Alice")
    equal(ranks.second.player, "Bob")
    equal(ranks.tied, true)
    equal(table.getn(ranks.ties), 2)
    equal(entry.winner, nil)
    equal(model:AddRoll(entry, "Alice", 88), false)
    equal(model:AddRoll(entry, "alice", 25), true)
    ranks = model:Rankings(entry)
    equal(ranks.highest.player, "Bob")
    equal(ranks.second.player, "Cara")
    equal(table.getn(entry.rolls), 3)
    equal(table.getn(entry.rollHistory), 4)
    model:SetChoice(entry, "Cara", "NEED")
    equal(entry.rollHistory[3].choice, "ROLL", "later choices cannot rewrite observed roll history")
end)

test("custom roll ranges remain separate from standard rolls", function()
    local model = tracker()
    local entry = model:StartItem(item(1), "master")
    model:AddRoll(entry, "Alice", 62, 1, 100)
    model:AddRoll(entry, "Bob", 88, 1, 100)
    model:AddRoll(entry, "Cara", 1000, 1, 1000)
    local ranks = model:Rankings(entry)
    equal(ranks.highest.player, "Bob")
    equal(ranks.second.player, "Alice")
    equal(ranks.mixedRanges, true)
    equal(table.getn(ranks.rangeGroups), 2)
    equal(model:Rankings(entry, {min = 1, max = 1000}).highest.player, "Cara")
    equal(model:AddRoll(entry, "Dan", 101, 1, 100), false)
    equal(model:AddRoll(entry, "Dan", 1.5, 1, 100), false)
    equal(model:AddRoll(entry, "Dan", 1, 10, 1), false)
end)

test("bid normalization accepts spelling formats without ordinary-chat guesses", function()
    local cases = {
        {"min", "MIN"}, {"  MiN! ", "MIN"}, {"m.i.n", "MIN"}, {"m 1 n", "MIN"},
        {"minimum", "MIN"}, {"NEED", "NEED"}, {"n e e d", "NEED"}, {"n33d!", "NEED"},
        {"NÉÉD", "NEED"}, {"NEEEEED!!!", "NEED"}, {"(MAX)", "MAX"}, {"M-A-X", "MAX"},
        {"m4x", "MAX"}, {"maximum", "MAX"}, {"bid: need", "NEED"},
        {item(1) .. " NEED!", "NEED"},
    }
    for _, row in ipairs(cases) do equal(GroupLoot.NormalizeBid(row[1]), row[2], row[1]) end
    for _, message in ipairs({"need healing", "I need this", "minimum dps", "max roll 100", "min-max", "maybe", "100", ""}) do
        equal(GroupLoot.NormalizeBid(message), nil, message)
    end
end)

test("actual receipt determines the EPGP winner and that player's last bid", function()
    local model = tracker()
    local entry = model:StartItem(item(1), "master")
    model:AddBid(entry, "Alice", "MAX")
    model:AddBid(entry, "Cara", "nEeD")
    model:AddBid(entry, "Cara", "m.i.n")
    model:AddRoll(entry, "Alice", 99)
    model:AddRoll(entry, "Cara", 5)
    equal(entry.method, "epgp")
    equal(entry.distributionMethod, "master")
    model:RecordObservedWinner(entry.id, "Alice", "Need", 99)
    equal(entry.observedWinner, "Alice")
    equal(entry.winner, nil)
    local awarded = model:Award(item(1), "Cara", {contextID = entry.id})
    equal(awarded, entry)
    equal(entry.winner, "Cara")
    equal(entry.recipient, "Cara")
    equal(entry.winnerBid, "MIN")
    equal(entry.winnerBidRaw, "m.i.n")
    equal(entry.state, "awarded")
end)

test("ambiguous same-item receipts stay unassigned and never borrow a bid", function()
    local model, db = tracker()
    local a = model:StartItem(item(1), "master")
    local b = model:StartItem(item(1), "master")
    model:AddBid(a, "Alice", "MIN")
    model:AddBid(b, "Alice", "MAX")
    local found, reason = model:Award(item(1), "Alice")
    equal(found, nil)
    equal(reason, "ambiguous")
    equal(table.getn(db.groupLoot.unassigned), 1)
    equal(db.groupLoot.unassigned[1].recipient, "Alice")
    equal(a.winner, nil)
    equal(b.winner, nil)
    found = model:Award(item(1), "Alice", {contextID = b.id})
    equal(found, b)
    equal(b.winnerBid, "MAX")
    equal(a.state, "open")
end)

test("awards validate item identity and live roll IDs beat reused history", function()
    local model = tracker()
    local a = model:StartItem(item(1), "group", {rollID = 9})
    local found, reason = model:Award(item(2), "Alice", {contextID = a.id})
    equal(found, nil)
    equal(reason, "item_mismatch")
    equal(a.winner, nil)
    model:Award(item(1), "Alice", {rollID = 9})
    found, reason = model:Award(item(1), "Alice", {rollID = 9})
    equal(found, a)
    equal(reason, "duplicate")
    local b = model:StartItem(item(1), "group", {rollID = 9})
    found = model:Award(item(1), "Bob", {rollID = 9})
    equal(found, b)
    equal(b.winner, "Bob")
end)

test("saved unresolved sessions cannot claim a later item after reload", function()
    local model, db = tracker()
    local entry = model:StartItem(item(1), "master", {select = true})
    model:AddBid(entry, "Alice", "MAX")
    equal(model:GetActive(), entry)
    local restored = tracker(db)
    equal(entry.state, "unassigned")
    equal(entry.closeReason, "session_restored")
    equal(restored:GetActive(), nil)
    equal(restored:ResolveContext(item(1)), nil)
    equal(table.getn(restored:Entries()), 1)
end)

test("reset uses the root database and preserves unrelated session settings", function()
    local model, db = tracker()
    db.ui = {width = 900}
    model:StartItem(item(1), "master", {select = true})
    model:Reset()
    equal(table.getn(model:Entries()), 0)
    equal(table.getn(model:GetUnassigned()), 0)
    equal(model:GetActive(), nil)
    equal(db.ui.width, 900)
    db.groupLoot = nil
    equal(model:StartItem(item(2), "group").id, 1)
end)

test("export includes methods choices rolls bids receipts and escaped text", function()
    local model = tracker()
    local entry = model:StartItem(item(1, "Sword"), "master", {name = "Sword\twith\nnewlines"})
    model:AddRoll(entry, "Alice", 88)
    model:AddRoll(entry, "Bob", 62)
    model:AddBid(entry, "Bob", "NEED")
    model:Award(item(1), "Bob", {contextID = entry.id})
    model:Award(item(2), "Cara")
    local exported = model:Export()
    assert(string.find(exported, "Sword\\twith\\nnewlines", 1, true))
    assert(string.find(exported, "\tepgp\tmaster\tawarded\tBob\tNEED", 1, true))
    assert(string.find(exported, "Alice\t88\tROLL\tBob\t62", 1, true))
    assert(string.find(exported, "Bob\tbid\tNEED", 1, true))
    assert(string.find(exported, "Unassigned item\tRecipient\tReason", 1, true))
    assert(not string.find(exported, "|Hitem", 1, true))
end)

test("a single custom roll range has leaders but mixed ranges are not combined", function()
    local model = tracker()
    local entry = model:StartItem(item(99), "master")
    model:AddRoll(entry, "Alice", 900, 1, 1000)
    model:AddRoll(entry, "Bob", 800, 1, 1000)
    local ranks = model:Rankings(entry)
    equal(ranks.highest.player, "Alice")
    equal(ranks.second.player, "Bob")
    equal(ranks.max, 1000)
    model:AddRoll(entry, "Cara", 8000, 1, 10000)
    ranks = model:Rankings(entry)
    equal(ranks.mixedRanges, true)
    equal(ranks.highest, nil)
    equal(table.getn(ranks.rangeGroups), 2)
end)

